# Compiles the frame generation shaders and embeds them into
# xenia/ui/vulkan/frame_generation_shaders.h. Requires glslangValidator and
# spirv-val in PATH.
import os, struct, subprocess
here = os.path.dirname(os.path.abspath(__file__))
names = ['fg_ingest', 'fg_down', 'fg_me', 'fg_me_coarse', 'fg_interp']
out = ['// Generated by xenia/ui/shaders/framegen/gen_header.py from the .comp',
       '// sources (glslangValidator -V --target-env vulkan1.1, spirv-val).',
       '#ifndef XENIA_UI_VULKAN_FRAME_GENERATION_SHADERS_H_',
       '#define XENIA_UI_VULKAN_FRAME_GENERATION_SHADERS_H_', '',
       '#include <cstdint>', '', 'namespace xe {', 'namespace ui {',
       'namespace vulkan {', 'namespace frame_generation_shaders {', '']
for name in names:
    src = os.path.join(here, name + '.comp')
    spv = os.path.join(here, name + '.spv')
    subprocess.check_call(['glslangValidator', '-V', '--target-env',
                           'vulkan1.1', '-o', spv, src],
                          stdout=subprocess.DEVNULL)
    subprocess.check_call(['spirv-val', '--target-env', 'vulkan1.1', spv])
    data = open(spv, 'rb').read()
    os.remove(spv)
    words = struct.unpack('<%dI' % (len(data) // 4), data)
    out.append('inline constexpr uint32_t %s[] = {' % name[3:])
    for i in range(0, len(words), 6):
        out.append('    ' + ', '.join('0x%08X' % w for w in words[i:i + 6]) + ',')
    out.append('};')
    out.append('')
out += ['}  // namespace frame_generation_shaders', '}  // namespace vulkan',
        '}  // namespace ui', '}  // namespace xe', '',
        '#endif  // XENIA_UI_VULKAN_FRAME_GENERATION_SHADERS_H_', '']
open(os.path.join(here, '..', '..', 'vulkan', 'frame_generation_shaders.h'),
     'w').write('\n'.join(out))
print('ok')
